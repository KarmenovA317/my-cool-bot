"""
ai_handler.py
Обработка свободных вопросов пользователя через Gemini API.

ВАЖНО: пакет google-generativeai, указанный в ТЗ, официально помечен как
deprecated — Google перевёл всех разработчиков на единый пакет google-genai
(тот же API-ключ Gemini, новый интерфейс клиента). Ниже используется
актуальный пакет: `pip install google-genai`, импорт `from google import genai`.
Логика и результат для пользователя — те же, что были бы с генеративной моделью
Gemini, просто через поддерживаемый SDK.
"""
import asyncio
import logging

from google import genai
from google.genai import types

from config import GEMINI_API_KEY, GEMINI_MODEL

logger = logging.getLogger(__name__)

SYSTEM_INSTRUCTION = """\
Ты — Shyntas.Bot, вежливый и грамотный технический консультант компании \
«Astana Shyntas» (г. Астана, Казахстан). Компания производит и монтирует \
современные алюминиевые конструкции: окна, двери, витражи, вентилируемые \
фасады, а также остекление балконов и лоджий.

Правила общения:
1. Отвечай полно и развёрнуто (3-6 предложений), по-деловому и дружелюбно, \
как живой эксперт компании, а не как обезличенный робот.
2. Хорошо ориентируйся в базовых преимуществах алюминия перед пластиком \
(ПВХ): выше прочность и долговечность (30+ лет службы), не деформируется от \
перепадов температуры и УФ-излучения, более тонкие и жёсткие рамы — больше \
света и остекления, подходит для больших панорамных конструкций и вентилируемых \
фасадов, экологичен и подлежит переработке, не желтеет и не теряет форму со временем.
3. Если вопрос касается услуг компании (окна, двери, витражи, фасады, \
остекление балконов) — подтверди, что Astana Shyntas это делает.
4. Всегда мягко и естественно подводи разговор к следующему шагу: предложи \
воспользоваться встроенным калькулятором стоимости в этом же боте (кнопка \
«Рассчитать стоимость») или оставить контакт для связи с менеджером.
5. Никогда не придумывай точные цены, сроки монтажа или технические \
характеристики, которых нет в этой инструкции — для точного расчёта всегда \
направляй на калькулятор бота или на менеджера.
6. Если вопрос не связан с алюминиевыми конструкциями, вежливо верни \
разговор в тему компании.
7. Отвечай на том языке, на котором пишет пользователь.
"""


async def ask_gemini(user_text: str) -> str:
    """
    Отправляет свободный вопрос пользователя в Gemini и возвращает текст ответа.

    Использует synchronous клиент в отдельном потоке (asyncio.to_thread), чтобы избежать
    проблем с кешированием состояния в асинхронном SDK, которые могут привести к урезанию
    ответов после нескольких запросов.
    """

    def _call_gemini_sync(text: str) -> str:
        # Создаём свежий клиент для каждого запроса, чтобы избежать побочных эффектов
        client = genai.Client(api_key=GEMINI_API_KEY)
        response = client.models.generate_content(
            model=GEMINI_MODEL,
            contents=text,
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_INSTRUCTION,
                temperature=0.8,  # Увеличена с 0.6 до 0.8 для более развёрнутых ответов
                max_output_tokens=1000,  # Увеличена с 500 до 1000 для возможности полных ответов
            ),
        )
        return (response.text or "").strip()

    try:
        text = await asyncio.to_thread(_call_gemini_sync, user_text)
        if not text:
            return (
                "Извините, не получилось сформулировать ответ. Могу сразу "
                "рассчитать предварительную стоимость конструкции — нажмите "
                "«Рассчитать стоимость»."
            )
        return text
    except Exception:
        logger.exception("Ошибка запроса к Gemini API")
        return (
            "Извините, сейчас не получается обработать вопрос автоматически. "
            "Хотите я передам его менеджеру или сразу перейдём к расчёту стоимости?"
        )